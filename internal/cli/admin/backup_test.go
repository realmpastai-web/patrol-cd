const examplesDir = "../../../examples"

// seedPatrol creates a representative Patrol CD configuration in ns from the examples:
// settings, projects, repositories, credential templates, clusters, SCM providers, an
// ApplicationSet with an owned Application, an Application with the cascade finalizer and
// an in-flight Operation, plus objects that are not part of the configuration.
func seedPatrol(t *testing.T, ctx contextT, ns string) map[resourceKey]bool {
	t.Helper()
	var objs []*unstructured.Unstructured
	settingsFiles := []string{"patrol-cm.yaml", "patrol-rbac-cm.yaml", "patrol-ssh-known-hosts-cm.yaml", "patrol-tls-certs-cm.yaml",
		"patrol-gpg-keys-cm.yaml", "patrol-notifications-cm.yaml", "patrol-notifications-secret.yaml", "patrol-secret.yaml"}
	for _, f := range settingsFiles {
		objs = append(objs, applyFile(t, ctx, ns, filepath.Join(examplesDir, "platform", "settings", f))...)
	}
	for _, dir := range []string{"projects", "repositories", "clusters", "scm"} {
		files, err := filepath.Glob(filepath.Join(examplesDir, "platform", dir, "*.yaml"))
		require.NoError(t, err)
		for _, f := range files {
			objs = append(objs, applyFile(t, ctx, ns, f)...)
		}
	}
	appset := applyFile(t, ctx, ns, filepath.Join(examplesDir, "apps", "appset-list", "applicationset.yaml"))[0]
	objs = append(objs, appset)
	objs = append(objs, applyFile(t, ctx, ns, filepath.Join(examplesDir, "apps", "plain-yaml", "application.yaml"))...)

	// An Application generated by the ApplicationSet (owned by it).
	owned := &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "Application",
		"metadata": map[string]any{"name": "guestbook-list-dev", "labels": map[string]any{"env": "dev"}},
		"spec": map[string]any{
			"project":     "default",
			"source":      map[string]any{"repoURL": "https://git.example.com/platform/patrol-examples.git", "path": "apps/helm-chart/chart", "targetRevision": "main"},
			"destination": map[string]any{"server": "https://kubernetes.default.svc", "namespace": "guestbook-dev"},
		},
	}}
	owned.SetOwnerReferences([]metav1.OwnerReference{{APIVersion: currentGroup + "/v1alpha1", Kind: "ApplicationSet", Name: appset.GetName(), UID: appset.GetUID(), Controller: ptrTo(true), BlockOwnerDeletion: ptrTo(true)}})
	objs = append(objs, createObject(t, ctx, ns, owned))

	// A credentials Secret managed by Patrol and owned by its Repository (API-created shape).
	repo := &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "Repository",
		"metadata": map[string]any{"name": "repo-managed"},
		"spec":     map[string]any{"url": "https://git.example.com/team/managed.git", "credentialsRef": map[string]any{"name": "repo-managed-creds"}},
	}}
	repo = createObject(t, ctx, ns, repo)
	objs = append(objs, repo)
	creds := &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "v1", "kind": "Secret",
		"metadata": map[string]any{
			"name":        "repo-managed-creds",
			"labels":      map[string]any{"cd.patrol.example/secret-type": "repository"},
			"annotations": map[string]any{"cd.patrol.example/managed-by": "patrol-cd"},
		},
		"stringData": map[string]any{"username": "git", "password": "s3cr3t-value"},
	}}
	creds.SetOwnerReferences([]metav1.OwnerReference{{APIVersion: currentGroup + "/v1alpha1", Kind: "Repository", Name: repo.GetName(), UID: repo.GetUID()}})
	objs = append(objs, createObject(t, ctx, ns, creds))

	// Not part of the configuration.
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "v1", "kind": "Secret", "metadata": map[string]any{"name": "unrelated"}, "stringData": map[string]any{"k": "unrelated-value"},
	}})
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "v1", "kind": "Secret", "metadata": map[string]any{"name": initialAdminSecretName}, "stringData": map[string]any{"password": "initial-pass"},
	}})
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "v1", "kind": "ConfigMap", "metadata": map[string]any{"name": "unrelated-cm"}, "data": map[string]any{"k": "v"},
	}})

	keys := map[resourceKey]bool{}
	for _, o := range objs {
		keys[keyOf(o)] = true
	}
	return keys
}

func ptrTo[T any](v T) *T { return &v }

// deleteConfiguration deletes every Patrol object and Patrol Secret/ConfigMap of keys,
// removing finalizers first (no controller runs in envtest).
func deleteConfiguration(t *testing.T, ctx contextT, keys map[resourceKey]bool) {
	t.Helper()
	for k := range keys {
		dc, err := resourceFor(envDyn, schemaGK(k), k.Namespace)
		require.NoError(t, err)
		_, err = dc.Patch(ctx, k.Name, types.MergePatchType, []byte(`{"metadata":{"finalizers":null,"ownerReferences":null}}`), metav1.PatchOptions{})
		if err != nil && !apierrors.IsNotFound(err) {
			require.NoError(t, err)
		}
		err = dc.Delete(ctx, k.Name, metav1.DeleteOptions{})
		if err != nil && !apierrors.IsNotFound(err) {
			require.NoError(t, err)
		}
	}
	for k := range keys {
		dc, _ := resourceFor(envDyn, schemaGK(k), k.Namespace)
		require.Eventually(t, func() bool {
			_, err := dc.Get(ctx, k.Name, metav1.GetOptions{})
			return apierrors.IsNotFound(err)
		}, 30e9, 100e6, "deleted %v", k)
	}
}

func TestExportImportRoundTrip(t *testing.T) {
	ctx := requireEnv(t)
	ns := newNamespace(t, ctx, "roundtrip")
	keys := seedPatrol(t, ctx, ns)
	tio := newTestIO(ns)

	backup := filepath.Join(t.TempDir(), "backup.yaml")
	require.NoError(t, tio.run(ctx, "admin", "export", "-o", backup))
	st, err := os.Stat(backup)
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o600), st.Mode().Perm(), "exports may hold credentials")
	assert.Contains(t, tio.errOut.String(), "WARNING: the export contains")

	data, err := os.ReadFile(backup)
	require.NoError(t, err)
	objs, err := splitObjects(data)
	require.NoError(t, err)
	exported := map[resourceKey]*unstructured.Unstructured{}
	for _, o := range objs {
		assert.Empty(t, o.GetUID(), "uid stripped")
		assert.Empty(t, o.GetResourceVersion(), "resourceVersion stripped")
		assert.Empty(t, o.GetManagedFields(), "managedFields stripped")
		_, hasStatus := o.Object["status"]
		assert.False(t, hasStatus, "status stripped: %s", objectRef(o))
		for _, ref := range o.GetOwnerReferences() {
			assert.Empty(t, ref.UID, "owner UIDs are rewritten on import")
		}
		o.SetNamespace(ns)
		exported[keyOf(o)] = o
	}
	for k := range keys {
		assert.Contains(t, exported, k, "exported %v", k)
	}
	for _, name := range []string{"unrelated", "unrelated-cm", initialAdminSecretName} {
		assert.NotContains(t, string(data), "name: "+name+"\n", "%s is not part of the configuration", name)
	}
	assert.Equal(t, len(keys), len(exported), "nothing else is exported")

	// Disaster: the configuration is gone.
	deleteConfiguration(t, ctx, keys)

	require.NoError(t, tio.run(ctx, "admin", "import", backup))
	out := tio.out.String()
	assert.Contains(t, out, "import process started "+ns)
	assert.Contains(t, out, "Import process completed successfully in namespace "+ns)
	assert.NotContains(t, out, "needs pruning")
	for k, bak := range exported {
		dc, err := resourceFor(envDyn, schemaGK(k), k.Namespace)
		require.NoError(t, err)
		live, err := dc.Get(ctx, k.Name, metav1.GetOptions{})
		require.NoError(t, err, "restored %v", k)
		assert.True(t, specsEqual(bak, live), "restored %v equals the backup", k)
		for _, ref := range live.GetOwnerReferences() {
			odc, err := resourceFor(envDyn, schemaGK(resourceKey{Group: groupOf(ref.APIVersion), Kind: ref.Kind}), k.Namespace)
			require.NoError(t, err)
			owner, err := odc.Get(ctx, ref.Name, metav1.GetOptions{})
			require.NoError(t, err)
			assert.Equal(t, owner.GetUID(), ref.UID, "owner reference of %v points at the restored owner", k)
		}
		if k.Kind == "Secret" || k.Kind == "Application" {
			assert.NotEmpty(t, live.GetName())
		}
	}
	// Secret data survives (credentials restored without re-entering them).
	sec, err := envKube.CoreV1().Secrets(ns).Get(ctx, "repo-managed-creds", metav1.GetOptions{})
	require.NoError(t, err)
	assert.Equal(t, "s3cr3t-value", string(sec.Data["password"]))
	require.Len(t, sec.OwnerReferences, 1)

	// Idempotent: a second import changes nothing.
	require.NoError(t, tio.run(ctx, "admin", "import", "--verbose", backup))
	out = tio.out.String()
	assert.NotContains(t, out, " created")
	assert.NotContains(t, out, " updated")
	assert.Contains(t, out, " unchanged")
}

func TestImportDryRunAndPrune(t *testing.T) {
	ctx := requireEnv(t)
	ns := newNamespace(t, ctx, "prune")
	keys := seedPatrol(t, ctx, ns)
	tio := newTestIO(ns)
	backup := filepath.Join(t.TempDir(), "backup.yaml")
	require.NoError(t, tio.run(ctx, "admin", "export", "-o", backup))

	// Changes after the backup: an extra project and application (with the cascade
	// finalizer), a changed project, a skipped extra project.
	extraApp := createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "Application",
		"metadata": map[string]any{"name": "extra-app", "finalizers": []any{"resources-finalizer.cd.patrol.example"}},
		"spec": map[string]any{"project": "default", "source": map[string]any{"repoURL": "https://git.example.com/x.git", "path": "."},
			"destination": map[string]any{"server": "https://kubernetes.default.svc", "namespace": "x"}},
	}})
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "AppProject", "metadata": map[string]any{"name": "extra-proj"}, "spec": map[string]any{},
	}})
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "AppProject",
		"metadata": map[string]any{"name": "keep-proj", "labels": map[string]any{"backup/skip": "true"}}, "spec": map[string]any{},
	}})
	_, err := envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Patch(ctx, "default", types.MergePatchType, []byte(`{"spec":{"description":"changed"}}`), metav1.PatchOptions{})
	require.NoError(t, err)

	// Dry run: reports, writes nothing.
	require.NoError(t, tio.run(ctx, "admin", "import", "--dry-run", "--prune", "--skip-resources-with-label", "backup/skip=true", backup))
	out := tio.out.String()
	assert.Contains(t, out, currentGroup+"/AppProject default in namespace "+ns+" updated (dry run)")
	assert.Contains(t, out, currentGroup+"/Application extra-app pruned (dry run)")
	assert.Contains(t, out, currentGroup+"/AppProject extra-proj pruned (dry run)")
	assert.Contains(t, out, "Skipping pruning of "+currentGroup+"/AppProject keep-proj")
	proj, err := envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Get(ctx, "default", metav1.GetOptions{})
	require.NoError(t, err)
	desc, _, _ := unstructured.NestedString(proj.Object, "spec", "description")
	assert.Equal(t, "changed", desc, "dry run writes nothing")
	_, err = envDyn.Resource(kindApplication.gvr(currentGroup)).Namespace(ns).Get(ctx, "extra-app", metav1.GetOptions{})
	require.NoError(t, err, "dry run deletes nothing")

	// Without --prune nothing is deleted.
	require.NoError(t, tio.run(ctx, "admin", "import", backup))
	out = tio.out.String()
	assert.Contains(t, out, currentGroup+"/Application extra-app needs pruning")
	assert.Contains(t, out, currentGroup+"/AppProject extra-proj needs pruning")
	_, err = envDyn.Resource(kindApplication.gvr(currentGroup)).Namespace(ns).Get(ctx, "extra-app", metav1.GetOptions{})
	require.NoError(t, err, "import never deletes without --prune")
	proj, err = envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Get(ctx, "default", metav1.GetOptions{})
	require.NoError(t, err)
	desc, _, _ = unstructured.NestedString(proj.Object, "spec", "description")
	assert.NotEqual(t, "changed", desc, "import restores the backed-up spec")

	// With --prune: extra objects go, the Application's cascade finalizer is removed first
	// (its resources are not deleted), labelled objects stay.
	require.NoError(t, tio.run(ctx, "admin", "import", "--prune", "--skip-resources-with-label", "backup/skip=true", backup))
	out = tio.out.String()
	assert.Contains(t, out, currentGroup+"/Application extra-app pruned")
	require.Eventually(t, func() bool {
		_, err := envDyn.Resource(kindApplication.gvr(currentGroup)).Namespace(ns).Get(ctx, "extra-app", metav1.GetOptions{})
		return apierrors.IsNotFound(err)
	}, 30e9, 100e6, "pruned application with finalizer is gone (finalizer removed first)")
	_, err = envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Get(ctx, "extra-proj", metav1.GetOptions{})
	assert.True(t, apierrors.IsNotFound(err))
	_, err = envDyn.Resource(kindAppProject.gvr(currentGroup)).Namespace(ns).Get(ctx, "keep-proj", metav1.GetOptions{})
	require.NoError(t, err, "skip label protects from pruning")
	_ = extraApp
	// Settings ConfigMaps and non-configuration objects are never pruned.
	_, err = envKube.CoreV1().Secrets(ns).Get(ctx, "unrelated", metav1.GetOptions{})
	require.NoError(t, err)
	for k := range keys {
		if k.Kind == "ConfigMap" {
			_, err := envKube.CoreV1().ConfigMaps(ns).Get(ctx, k.Name, metav1.GetOptions{})
			require.NoError(t, err)
		}
	}
}

func TestExportWithoutSecretsAndWithOperations(t *testing.T) {
	ctx := requireEnv(t)
	ns := newNamespace(t, ctx, "nosecrets")
	seedPatrol(t, ctx, ns)
	op := createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "Operation",
		"metadata": map[string]any{"name": "guestbook-plain-sync-1"},
		"spec":     map[string]any{"application": "guestbook-plain", "sync": map[string]any{"revision": "main"}},
	}})
	tio := newTestIO(ns)
	require.NoError(t, tio.run(ctx, "admin", "export", "--include-secrets=false", "--include-operations"))
	out := tio.out.String()
	assert.NotContains(t, out, "kind: Secret")
	assert.NotContains(t, tio.errOut.String(), "WARNING: the export contains")
	assert.Contains(t, out, "kind: Operation")
	assert.Contains(t, out, "name: "+op.GetName())

	// Operations are never re-created by import; --stop-operation cancels in-flight ones.
	backup := filepath.Join(t.TempDir(), "b.yaml")
	require.NoError(t, os.WriteFile(backup, []byte(out), 0o600))
	require.NoError(t, envDyn.Resource(kindOperation.gvr(currentGroup)).Namespace(ns).Delete(ctx, op.GetName(), metav1.DeleteOptions{}))
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "Operation",
		"metadata": map[string]any{"name": "inflight"},
		"spec":     map[string]any{"application": "guestbook-plain", "sync": map[string]any{"revision": "main"}},
	}})
	require.NoError(t, tio.run(ctx, "admin", "import", "--stop-operation", backup))
	out = tio.out.String()
	assert.Contains(t, out, "Skipping "+currentGroup+"/Operation "+op.GetName())
	assert.Contains(t, out, currentGroup+"/Operation inflight of application guestbook-plain in namespace "+ns+" stopped")
	_, err := envDyn.Resource(kindOperation.gvr(currentGroup)).Namespace(ns).Get(ctx, op.GetName(), metav1.GetOptions{})
	assert.True(t, apierrors.IsNotFound(err), "operations from a backup are not re-created")
	live, err := envDyn.Resource(kindOperation.gvr(currentGroup)).Namespace(ns).Get(ctx, "inflight", metav1.GetOptions{})
	require.NoError(t, err)
	cancel, _, _ := unstructured.NestedBool(live.Object, "spec", "cancel")
	assert.True(t, cancel)
	// Without Secrets in the backup, live Patrol Secrets are kept and reported as such.
	assert.Contains(t, out, "/Secret patrol-secret is not in the backup; not pruned: patrol-secret and patrol-notifications-secret are never pruned")
	assert.Contains(t, out, "/Secret repo-managed-creds is not in the backup; not pruned: the backup contains no Secrets")
	assert.NotContains(t, out, "/Secret repo-managed-creds needs pruning")
}

// rewriteBackup rewrites the backup at path without the objects drop selects.
func rewriteBackup(t *testing.T, path string, drop func(*unstructured.Unstructured) bool) {
	t.Helper()
	data, err := os.ReadFile(path)
	require.NoError(t, err)
	objs, err := splitObjects(data)
	require.NoError(t, err)
	var buf strings.Builder
	dropped := 0
	for _, o := range objs {
		if drop(o) {
			dropped++
			continue
		}
		require.NoError(t, writeBackupObject(&buf, o))
	}
	require.NotZero(t, dropped, "the backup contains the objects to drop")
	require.NoError(t, os.WriteFile(path, []byte(buf.String()), 0o600))
}

func isObject(kind, name string) func(*unstructured.Unstructured) bool {
	return func(o *unstructured.Unstructured) bool { return o.GetKind() == kind && o.GetName() == name }
}

// Regression: "import --prune" of a backup exported with --include-secrets=false deleted
// every Patrol Secret (patrol-secret included: admin lockout, lost credentials).
func TestImportPruneOfSecretlessBackupKeepsSecrets(t *testing.T) {
	ctx := requireEnv(t)
	ns := newNamespace(t, ctx, "secretless")
	keys := seedPatrol(t, ctx, ns)
	tio := newTestIO(ns)
	backup := filepath.Join(t.TempDir(), "b.yaml")
	require.NoError(t, tio.run(ctx, "admin", "export", "--include-secrets=false", "-o", backup))

	for _, args := range [][]string{{"--dry-run", "--prune"}, {"--prune"}} {
		require.NoError(t, tio.run(ctx, append(append([]string{"admin", "import"}, args...), backup)...))
		out := tio.out.String()
		assert.NotRegexp(t, `(?m)^/Secret \S+ pruned`, out, "no Secret is pruned (%v)", args)
		assert.Contains(t, out, "/Secret patrol-secret is not in the backup; not pruned: patrol-secret and patrol-notifications-secret are never pruned")
		assert.Contains(t, out, "/Secret patrol-notifications-secret is not in the backup; not pruned")
		assert.Contains(t, out, "/Secret repo-managed-creds is not in the backup; not pruned: the backup contains no Secrets (exported with --include-secrets=false?)")
	}
	n := 0
	for k := range keys {
		if k.Kind != "Secret" {
			continue
		}
		n++
		_, err := envKube.CoreV1().Secrets(ns).Get(ctx, k.Name, metav1.GetOptions{})
		require.NoError(t, err, "Secret %s survives the import", k.Name)
	}
	assert.Greater(t, n, 3)
}

// Regression: import --prune deleted unlabelled Secrets that live Patrol objects merely
// reference (shared with other workloads), and patrol-secret when a backup lacked it.
func TestImportPruneSecretScope(t *testing.T) {
	ctx := requireEnv(t)
	ns := newNamespace(t, ctx, "secretscope")
	seedPatrol(t, ctx, ns)
	tio := newTestIO(ns)
	backup := filepath.Join(t.TempDir(), "b.yaml")
	require.NoError(t, tio.run(ctx, "admin", "export", "-o", backup))
	rewriteBackup(t, backup, isObject("Secret", "patrol-secret"))

	// Created after the backup: a Repository using an unlabelled shared Secret, and a
	// Patrol-managed credentials Secret.
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "v1", "kind": "Secret", "metadata": map[string]any{"name": "shared-token"}, "stringData": map[string]any{"password": "shared-value"},
	}})
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": currentGroup + "/v1alpha1", "kind": "Repository",
		"metadata": map[string]any{"name": "late-repo"},
		"spec":     map[string]any{"url": "https://git.example.com/team/late.git", "credentialsRef": map[string]any{"name": "shared-token"}},
	}})
	createObject(t, ctx, ns, &unstructured.Unstructured{Object: map[string]any{
		"apiVersion": "v1", "kind": "Secret",
		"metadata":   map[string]any{"name": "late-creds", "labels": map[string]any{"cd.patrol.example/secret-type": "repository"}},
		"stringData": map[string]any{"password": "late-value"},
	}})

	require.NoError(t, tio.run(ctx, "admin", "import", "--prune", backup))
	out := tio.out.String()
	assert.Contains(t, out, currentGroup+"/Repository late-repo pruned")
	assert.Contains(t, out, "/Secret late-creds pruned")
	assert.Contains(t, out, "/Secret shared-token is not in the backup; not pruned: not managed by Patrol CD (no cd.patrol.example/secret-type label or cd.patrol.example/managed-by: patrol-cd annotation)")
	assert.Contains(t, out, "/Secret patrol-secret is not in the backup; not pruned: patrol-secret and patrol-notifications-secret are never pruned")
	sec, err := envKube.CoreV1().Secrets(ns).Get(ctx, "shared-token", metav1.GetOptions{})
	require.NoError(t, err, "a referenced but unmanaged Secret is never pruned")
	assert.Equal(t, "shared-value", string(sec.Data["password"]))
	_, err = envKube.CoreV1().Secrets(ns).Get(ctx, "patrol-secret", metav1.GetOptions{})
	require.NoError(t, err, "patrol-secret is never pruned")
	_, err = envKube.CoreV1().Secrets(ns).Get(ctx, "late-creds", metav1.GetOptions{})
	assert.True(t, apierrors.IsNotFound(err), "a managed Secret not in the backup is pruned")
}

// ownerUIDs returns the owner UIDs of an object.
func ownerUIDs(obj *unstructured.Unstructured) []types.UID {
	var out []types.UID
	for _, r := range obj.GetOwnerReferences() {
		out = append(out, r.UID)
	}
	return out
}

